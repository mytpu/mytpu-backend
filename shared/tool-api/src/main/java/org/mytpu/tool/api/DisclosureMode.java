package org.mytpu.tool.api;

/** Сколько личного уходит вызывающему (specs/personal-data-for-agents, «Режимы выдачи»). */
public enum DisclosureMode {
    /** Поля как есть. */
    FULL,
    /** Личные поля по маске, безопасная фраза. */
    MASKED,
    /** Только безопасная фраза и ссылка на карточку «Мой ТПУ». */
    REFERENCE,
    /** Нет согласия — отказ со ссылкой на экран согласия. */
    DENY
}
