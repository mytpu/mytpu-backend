package org.mytpu.tool.api;

/**
 * Уровень доверия к модели, которая увидит ответ (docs/SECURITY.md, раздел 6). Свои клиенты (сайт, мобилка)
 * показывают данные человеку, а не модели, — для них решает канал, а не уровень.
 */
public enum Trust {
    /** Модель пользователя через MCP: Claude, ChatGPT, свой агент. */
    EXTERNAL,
    /** Модель на серверах ТПУ. */
    TRUSTED_TPU,
    /** Российский провайдер по договору поручения. */
    TRUSTED_CONTRACT,
    /** Провайдер без договора. */
    UNTRUSTED
}
