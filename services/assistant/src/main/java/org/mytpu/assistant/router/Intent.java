package org.mytpu.assistant.router;

/**
 * Категории намерений пользователя (specs/assistant/spec.md, шаг 6).
 */
public enum Intent {
    /** Поиск расположения аудитории, корпуса или подразделения ТПУ */
    ROOM_WHERE,
    /** Расписание занятий, сессий, пар группы или преподавателя */
    SCHEDULE,
    /** Инструкции и документы ТПУ: справки, отпуск, стипендии, перевод и т. д. */
    DOCS_HOWTO,
    /** Приветствие, благодарность или вопрос «кто ты» */
    GREETING,
    /** Вопросы вне контекста университета и обучения */
    OTHER
}
